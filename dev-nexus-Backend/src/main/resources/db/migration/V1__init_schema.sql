-- users table
CREATE TABLE users (
                       id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       uuid          UUID         NOT NULL,
                       email         VARCHAR(255) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       first_name    VARCHAR(255) NOT NULL,
                       last_name     VARCHAR(255) NOT NULL,
                       enabled       BOOLEAN      NOT NULL,
                       created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       CONSTRAINT uq_users_uuid  UNIQUE (uuid),
                       CONSTRAINT uq_users_email UNIQUE (email)
);

-- roles table
CREATE TABLE roles (
                       id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name        VARCHAR(255) NOT NULL,
                       description VARCHAR(255),
                       CONSTRAINT uq_roles_name UNIQUE (name),
                       CONSTRAINT ck_roles_name CHECK (name IN ('OWNER', 'ADMIN', 'MEMBER'))
);

INSERT INTO roles (name, description) VALUES
                                          ('OWNER',  'Full control, including deleting the organization or project'),
                                          ('ADMIN',  'Can manage members and settings'),
                                          ('MEMBER', 'Can work on tasks and comment');

-- organizations table
CREATE TABLE organizations (
                               id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               uuid        UUID         NOT NULL,
                               name        VARCHAR(255) NOT NULL,
                               description TEXT         NOT NULL,
                               created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               CONSTRAINT uq_organizations_uuid UNIQUE (uuid)
);

-- organization_members table
CREATE TABLE organization_members (
                                      id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      joined_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                      organization_id BIGINT    NOT NULL,
                                      user_id         BIGINT    NOT NULL,
                                      role_id         INTEGER   NOT NULL,
                                      CONSTRAINT uq_org_members_org_user UNIQUE (organization_id, user_id),
                                      CONSTRAINT fk_org_members_org  FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
                                      CONSTRAINT fk_org_members_user FOREIGN KEY (user_id)         REFERENCES users (id),
                                      CONSTRAINT fk_org_members_role FOREIGN KEY (role_id)         REFERENCES roles (id)
);

CREATE INDEX idx_org_members_user ON organization_members (user_id);

-- projects table
CREATE TABLE projects (
                          id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          project_key      VARCHAR(255) NOT NULL,
                          name             VARCHAR(255) NOT NULL,
                          description      TEXT,
                          next_task_number INTEGER      NOT NULL DEFAULT 0,
                          created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          organization_id  BIGINT       NOT NULL,
                          CONSTRAINT uq_projects_key UNIQUE (project_key),
                          CONSTRAINT fk_projects_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE
);

CREATE INDEX idx_projects_org ON projects (organization_id);

-- project_members table
CREATE TABLE project_members (
                                 id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 joined_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 project_id BIGINT    NOT NULL,
                                 user_id    BIGINT    NOT NULL,
                                 role_id    INTEGER   NOT NULL,
                                 CONSTRAINT uq_project_members_project_user UNIQUE (project_id, user_id),
                                 CONSTRAINT fk_project_members_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
                                 CONSTRAINT fk_project_members_user    FOREIGN KEY (user_id)    REFERENCES users (id),
                                 CONSTRAINT fk_project_members_role    FOREIGN KEY (role_id)    REFERENCES roles (id)
);

CREATE INDEX idx_project_members_user ON project_members (user_id);

-- tasks table
CREATE TABLE tasks (
                       id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       uuid        UUID         NOT NULL,
                       task_number INTEGER      NOT NULL,
                       title       VARCHAR(255) NOT NULL,
                       description TEXT,
                       status      VARCHAR(255) NOT NULL DEFAULT 'TO_DO',
                       priority    VARCHAR(255) NOT NULL DEFAULT 'MEDIUM',
                       due_date    DATE,
                       created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       deleted_at  TIMESTAMP,
                       project_id  BIGINT       NOT NULL,
                       assignee_id BIGINT,
                       CONSTRAINT uq_tasks_uuid UNIQUE (uuid),
                       CONSTRAINT uq_tasks_project_number UNIQUE (project_id, task_number),
                       CONSTRAINT ck_tasks_status   CHECK (status   IN ('TO_DO', 'IN_PROGRESS', 'IN_REVIEW', 'DONE')),
                       CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOWEST', 'LOW', 'MEDIUM', 'HIGH', 'HIGHEST')),
                       CONSTRAINT fk_tasks_project  FOREIGN KEY (project_id)  REFERENCES projects (id) ON DELETE CASCADE,
                       CONSTRAINT fk_tasks_assignee FOREIGN KEY (assignee_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_tasks_project_active ON tasks (project_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_tasks_assignee       ON tasks (assignee_id);

-- comments table
CREATE TABLE comments (
                          id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          uuid       UUID      NOT NULL,
                          content    TEXT      NOT NULL,
                          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          deleted_at TIMESTAMP,
                          task_id    BIGINT    NOT NULL,
                          author_id  BIGINT    NOT NULL,
                          CONSTRAINT uq_comments_uuid UNIQUE (uuid),
                          CONSTRAINT fk_comments_task   FOREIGN KEY (task_id)   REFERENCES tasks (id) ON DELETE CASCADE,
                          CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE INDEX idx_comments_task   ON comments (task_id);
CREATE INDEX idx_comments_author ON comments (author_id);